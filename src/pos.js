export function createPosApp() {
  const state = { cart: [], invoiceItems: [], invoiceDraftId: null, search: '', category: '', expandedSale: 0, paymentMethod: '',
    sharedTenantId: '', pendingInventoryEvents: 0, inventorySyncError: '', discount: 0, discountDialogOpen: false, activeTicketId: '',
    variantPickerProductId: 0,
    suppliers: [], purchases: [], tickets: [], cloudSales: [], quotations: [], cloudSyncError: '', cloudScopeId: 'local',
    nearbySyncStatus: '' };
  let initialized = false;
  // --- till module wiring (generated by the split; order matters) ---
  const {
    commonHeader, pageEnd, card, field, select, button, editIcon, deleteIcon, iconButton, iconLink,
    statusTag, empty, tabsTitle, metric, toast
  } = createTillUi();
  const {
    cartLineKey, addProductToCart
  } = createTillCart({ state, updateCartPanel: (...args) => updateCartPanel(...args) });
  const {
    renderStore, updateCartPanel, renderProductTiles
  } = createSellScreen({ state, button, empty, cartLineKey, renderCurrent, field });
  const {
    renderInventory
  } = createCatalogueInventoryScreen({
    state, renderSuppliers: (...args) => renderSuppliers(...args), tabsTitle, card, button, field,
    select, iconButton, editIcon, deleteIcon, iconLink, statusTag
  });
  const {
    renderSuppliers
  } = createCatalogueSuppliersScreen({ state, tabsTitle, card, field, select, empty, button, statusTag });
  const {
    renderSales
  } = createSalesScreen({ state, tabsTitle, metric, empty, card, statusTag, field, select });
  const { renderCustomers } = createCustomersScreen({ tabsTitle, card, state });
  const {
    renderInvoices
  } = createInvoicesScreen({ state, tabsTitle, card, field, empty, button, statusTag });
  const {
    renderInstances
  } = createInstancesScreen({ state, tabsTitle, card, statusTag, field, select, button, metric });
  const { renderOrders } = createOrdersScreen({ tabsTitle, card, state, button });
  const {
    renderQuotations
  } = createQuotationsScreen({ state, tabsTitle, card, field, statusTag, button });
  const { renderMore } = createMoreScreen({ tabsTitle, card });
  const {
    renderOverview
  } = createOverviewScreen({
    state, card, renderRevenueChart: (...args) => renderRevenueChart(...args), metric,
    renderProfitChart: (...args) => renderProfitChart(...args)
  });
  const { renderRevenueChart, renderProfitChart } = createOverviewCharts();
  const {
    renderSettings
  } = createSettingsScreen({ state, tabsTitle, card, field, button, select });
  const {
    saveCheckout
  } = createTillCheckout({
    state, toast, refresh, queueCloudRecord: (...args) => queueCloudRecord(...args),
    syncInventorySales: (...args) => syncInventorySales(...args),
    queueProduct: (...args) => queueProduct(...args)
  });
  const {
    queueProduct, queueCategory, queueExpense, queueSettings, seedCatalogueSync,
    seedCloudCatalogueForTenant, applyRemoteChange
  } = createSyncRecords({ queueCloudRecord: (...args) => queueCloudRecord(...args), state });
  const {
    queueCloudRecord, syncCloudBusinessRecords, getCloudSyncStatus, syncCloudNow,
    disconnectCloudSync, switchCloudSyncTenant, replaceWithCloudShop
  } = createCloudSync({
    state, sendNearbyChange: (...args) => sendNearbyChange(...args), seedCloudCatalogueForTenant,
    applyRemoteChange, refresh
  });
  const {
    createCategory, renameCategory, deleteCategory
  } = createCatalogueCategoryActions({ queueCategory, loadState, queueProduct });
  const {
    sendNearbyChange, startBluetoothNearbySync, startNearbySync, stopNearbySync
  } = createNearbySync({ state, applyRemoteChange, seedCatalogueSync, loadState, refresh });
  const {
    receivePurchaseOrder, syncInventorySales, syncSharedStock
  } = createInventorySync({ state, queueProduct, refresh });
  const {
    exportInventory, handleFileChange
  } = createInventoryBackup({ queueProduct, queueCategory, toast, refresh });
  const {
    readImageFile, getProductVision, createProductImageEmbedding, prepareImageForVision,
    captureProductPhoto, captureVideoFrameForVision, embeddingBase64ToHex
  } = createProductPhotos({ queueProduct, loadState, toast });
  const {
    scanPhotoMatchFrames, scanLabelFrames
  } = createScannerFrames({
    captureVideoFrameForVision, getProductVision, embeddingBase64ToHex, state,
    createProductImageEmbedding, addProductToSale: (...args) => addProductToSale(...args),
    queueProduct, refresh, toast
  });
  const { printDocument, receiptHtml, quotationHtml, invoiceHtml } = createTillReceipts({ toast });
  const {
    handleSubmit
  } = createSubmitActions({
    refresh, state, renderCurrent, queueCategory, toast, queueSettings, queueExpense,
    readImageFile, queueProduct, createProductImageEmbedding, queueCloudRecord, saveCheckout,
    updateCartPanel
  });
  const {
    handleClick, syncInvoicePayments
  } = createClickActions({
    openBarcodeScanner: (...args) => openBarcodeScanner(...args), toast, refresh,
    captureProductPhoto, readImageFile, prepareImageForVision, getProductVision, state,
    addScannedBarcode: (...args) => addScannedBarcode(...args), updateCartPanel, queueCloudRecord,
    queueProduct, receivePurchaseOrder, seedCloudCatalogueForTenant, syncCloudBusinessRecords,
    startBluetoothNearbySync, stopNearbySync, startNearbySync, addProductToCart, cartLineKey,
    renderCurrent, queueCategory, renderKeepingForm, syncInventorySales, printDocument,
    quotationHtml, queueExpense, receiptHtml, invoiceHtml, exportInventory, syncSharedStock
  });
  const {
    handleInput
  } = createInputActions({ state, renderProductTiles, cartLineKey, updateCartPanel, renderKeepingForm });
  const tillScanner = createTillScanner({ toast, state, updateCartPanel, scanLabelFrames, scanPhotoMatchFrames });
  const {
    findProductByCode, addScannedBarcode, addProductToSale, openBarcodeScanner,
    handleScannerKeydown
  } = tillScanner;
  // --- end till module wiring ---

  function render(path = '/pos', params = new URLSearchParams()) {
    const route = path.startsWith('/pos/') ? path : '/pos';
    const screen = route.slice('/pos'.length) || '/';
    return `${commonHeader(route, params)}${screen === '/' ? renderStore() :
      screen === '/inventory' || screen.startsWith('/catalogue') ? renderInventory(params, screen) :
      screen === '/sales' ? renderSales(params) :
      screen === '/customers' ? renderCustomers() :
      screen === '/invoices' || screen === '/orders/invoices' ? renderInvoices(params) :
      screen === '/orders' ? renderOrders() :
      screen === '/orders/quotations' ? renderQuotations() :
      screen === '/instances' || screen === '/more/instances' ? renderInstances(params) :
      screen === '/settings' || screen === '/more/settings' ? renderSettings(params) :
      screen === '/more' ? renderMore() :
      screen === '/overview' ? renderOverview(params) : empty('POS page not found', 'Choose a section above.')}${pageEnd}`;
  }

  async function refresh() {
    const path = (window.location.hash || '#/pos').slice(1).split('?')[0] || '/pos';
    if (!path.startsWith('/pos')) return;
    await loadState();
    renderCurrent();
    // A customer may have paid an invoice's pay link since the screen was last open.
    if (path.startsWith('/pos/orders/invoices') || path.startsWith('/pos/invoices')) void syncInvoicePayments();
  }

  // Re-rendering a form to show a changed line item must not throw away what was already typed in it.
  function renderKeepingForm(formName) {
    const typed = [...(document.querySelector?.(`form[data-pos-form="${formName}"]`)?.elements || [])]
      .filter((element) => element.name && element.type !== 'hidden' && element.type !== 'file')
      .map((element) => [element.name, element.type === 'checkbox' ? element.checked : element.value]);
    renderCurrent();
    const form = document.querySelector?.(`form[data-pos-form="${formName}"]`);
    if (!form) return;
    for (const [name, value] of typed) {
      const element = form.elements[name];
      if (!element || element.type === 'hidden') continue;
      if (element.type === 'checkbox') element.checked = value;
      else element.value = value;
    }
  }

  function renderCurrent() {
    const hash = window.location.hash || '#/pos';
    const path = hash.slice(1).split('?')[0] || '/pos';
    if (!path.startsWith('/pos')) return;
    const params = new URLSearchParams(hash.split('?')[1] || '');
    const app = document.getElementById('app');
    if (app) {
      app.innerHTML = render(path, params);
      bindProductTaxonomyFields(app);
      const variantFields = app.querySelector?.('[data-product-variant-fields]');
      if (variantFields) bindProductVariantFields(variantFields);
      const pricingFields = app.querySelector?.('[data-attribute-pricing]');
      if (pricingFields) {
        bindAttributePricingFields(pricingFields, () => readAvailableTaxonomyAttributes(pricingFields.closest('form') || app));
        // The listener goes on the form, which is replaced on every render, so none ever stack up.
        pricingFields.closest('form')?.addEventListener('product-taxonomy-change', () => {
          pricingFields.refreshAttributePricing?.();
        });
      }
    }
  }

  async function loadState() {
    const [products, categories, settings, sales, invoices, instances, expenses, cash, closes, payments,
      sharedTenant, queuedEvents, queueError, quotations] = await Promise.all([
      listProducts(), listCategories(), getSettings(), listSales(), listInvoices(), listInstances(),
      rows('SELECT * FROM pos_expenses ORDER BY expense_date DESC,id DESC'),
      rows('SELECT * FROM pos_cash_movements ORDER BY created_at DESC LIMIT 30'),
      rows('SELECT * FROM pos_till_closes ORDER BY close_date DESC,id DESC LIMIT 20'),
      rows(`SELECT p.amount_cents,p.method,p.created_at,s.currency FROM pos_sale_payments p
        JOIN pos_sales s ON s.id=p.sale_id WHERE p.status='confirmed'`),
      rows("SELECT value FROM pos_settings WHERE key='shared_tenant_id'"),
      rows("SELECT COUNT(*) AS count FROM pos_inventory_queue WHERE status!='synced'"),
      rows("SELECT last_error FROM pos_inventory_queue WHERE last_error IS NOT NULL ORDER BY updated_at DESC LIMIT 1"),
      listQuotations()
    ]);
    state.products = products;
    state.categories = categories;
    state.settings = settings;
    state.sales = sales;
    state.cloudScopeId = settings.cloudSyncTenantId
      || window.EshopInventoryBridge?.activeWebsiteId?.() || 'local';
    [state.suppliers, state.purchases, state.tickets, state.cloudSales] = await Promise.all([
      listBusinessRecords('supplier', state.cloudScopeId), listBusinessRecords('purchase', state.cloudScopeId),
      listBusinessRecords('ticket', state.cloudScopeId), listBusinessRecords('sale', state.cloudScopeId)
    ]);
    state.cloudSyncError = settings.cloudSyncError;
    state.invoices = invoices;
    state.quotations = quotations;
    state.instances = instances;
    state.expenses = expenses;
    state.cashMovements = cash;
    state.tillCloses = closes;
    state.payments = payments;
    state.sharedTenantId = sharedTenant[0]?.value || '';
    state.pendingInventoryEvents = Number(queuedEvents[0]?.count || 0);
    state.inventorySyncError = queueError[0]?.last_error || '';
    if (state.sharedTenantId && window.EshopInventoryBridge?.hasTenantOwnerKey?.(state.sharedTenantId) === false) {
      state.inventorySyncError = '';
    }
    const summaries = await Promise.all(instances.map(async (instance) =>
      [instance.id, await instanceTotals(instance, settings.currency)]));
    state.instanceSummaries = new Map(summaries);
  }

  async function init() {
    if (initialized) return;
    initialized = true;
    await initializePosDatabase();
    await loadState();
    document.addEventListener('submit', handleSubmit);
    document.addEventListener('click', handleClick);
    document.addEventListener('keydown', handleScannerKeydown);
    document.addEventListener('input', handleInput);
    document.addEventListener('change', handleInput);
    document.addEventListener('change', handleFileChange);
    document.addEventListener('visibilitychange', () => {
      if (document.visibilityState === 'visible' &&
          (window.location.hash || '').slice(1).split('?')[0] === '/pos/overview') {
        void refresh();
      }
    });
    window.addEventListener('online', () => {
      void syncInventorySales().then(() => refresh()).catch((error) => {
        toast(error instanceof Error ? error.message : 'Could not sync POS inventory.', true);
      });
    });
    window.setInterval(() => {
      if (navigator.onLine !== false && state.sharedTenantId) {
        void syncInventorySales().then(() => refresh()).catch((error) => {
          toast(error instanceof Error ? error.message : 'Could not sync POS inventory.', true);
        });
      }
    }, 30000);
    void syncInventorySales();
    void syncCloudBusinessRecords().catch((error) => {
      state.cloudSyncError = error instanceof Error ? error.message : 'Cloud sync failed.';
    });
    window.addEventListener('online', () => {
      void syncCloudBusinessRecords().then(() => refresh()).catch((error) => {
        state.cloudSyncError = error instanceof Error ? error.message : 'Cloud sync failed.';
      });
    });
    window.setInterval(() => {
      if (state.settings?.cloudSyncEnabled && document.visibilityState !== 'hidden') {
        void syncCloudBusinessRecords().then(() => {
          const path = (window.location.hash || '').slice(1).split('?')[0];
          if (['/pos', '/pos/catalogue', '/pos/catalogue/products', '/pos/catalogue/suppliers',
            '/pos/orders', '/pos/sales'].includes(path)) return refresh();
          return undefined;
        }).catch((error) => {
          state.cloudSyncError = error instanceof Error ? error.message : 'Cloud sync failed.';
        });
      }
    }, 5000);
    const closeScannerOnLeave = () => {
      if (tillScanner.barcodeScanner) {
        void tillScanner.barcodeScanner.close().catch((error) => toast(error instanceof Error ? error.message : 'Could not stop the scanner.', true));
      }
    };
    window.addEventListener('pagehide', closeScannerOnLeave);
    window.addEventListener('hashchange', () => {
      closeScannerOnLeave();
      if ((window.location.hash || '').slice(1).split('?')[0].startsWith('/pos')) void refresh();
    });
    window.setInterval(() => {
      if ((window.location.hash || '').slice(1).split('?')[0] === '/pos/instances') void refresh();
    }, 15000);
  }

  return {
    init, render, refresh, recordSharedLocalSale, syncInventory: syncInventorySales,
    saveSale, reverseSale, listInvoices, saveInvoice, markInvoicePaid,
    listQuotations, saveQuotation, deleteQuotation, convertQuotationToInvoice,
    recordSharedStockUpdate, applyMainStoreAllocations, saveProduct, listProducts, listCategories, listSales, listExpenses, listInstances,
    getCloudSyncStatus, syncCloudNow, switchCloudSyncTenant, replaceWithCloudShop, disconnectCloudSync, stopNearbySync,
    getSettings, addCategory, createCategory, renameCategory, deleteCategory, deleteProduct, listBusinessRecords, findProductByCode, addScannedBarcode
  };
}
