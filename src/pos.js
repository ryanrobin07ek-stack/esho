  // Re-rendering a form to show a changed line item must not throw away what was already typed in it.
  function renderKeepingForm(formName) {
    const typed = [...(document.querySelector?.(`form[data-pos-form="${formName}"]`)?.elements || [])]
      .filter((element) => element.name && element.type !== 'hidden' && element.type !== 'file')
      .map((element) => [element.name, element.type === 'checkbox' ? element.checked : element.value]);
    renderCurrent();
    const form = document.querySelector?.(`form[data-pos-form="${formName}"]`);
    if (!form) return;
    for (const [name, value] of typed) {
      const element = form.elements[name];
      if (!element || element.type === 'hidden') continue;
      if (element.type === 'checkbox') element.checked = value;
      else element.value = value;
    }
  }

  function renderCurrent() {
    const hash = window.location.hash || '#/pos';
    const path = hash.slice(1).split('?')[0] || '/pos';
    if (!path.startsWith('/pos')) return;
    const params = new URLSearchParams(hash.split('?')[1] || '');
    const app = document.getElementById('app');
    if (app) {
      app.innerHTML = render(path, params);
      bindProductTaxonomyFields(app);
      const variantFields = app.querySelector?.('[data-product-variant-fields]');
      if (variantFields) bindProductVariantFields(variantFields);
      const pricingFields = app.querySelector?.('[data-attribute-pricing]');
      if (pricingFields) {
        bindAttributePricingFields(pricingFields, () => readAvailableTaxonomyAttributes(pricingFields.closest('form') || app));
        // The listener goes on the form, which is replaced on every render, so none ever stack up.
        pricingFields.closest('form')?.addEventListener('product-taxonomy-change', () => {
          pricingFields.refreshAttributePricing?.();
        });
      }
    }
  }

